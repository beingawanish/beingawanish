#!/usr/bin/env python3
"""Contract tooling for eda-commerce.

The .avsc files under contracts/avro and the catalogue in contracts/topics.yaml are the
sources. Everything else in contracts/ that this script writes is generated.

    python contracts/tools/contracts.py validate        # lint schemas and catalogue
    python contracts/tools/contracts.py bundle          # write contracts/avro-bundled (self-contained schemas)
    python contracts/tools/contracts.py examples        # write contracts/examples (*.json + raw Avro *.bin)
    python contracts/tools/contracts.py asyncapi        # write contracts/asyncapi/asyncapi.yaml
    python contracts/tools/contracts.py topics-conf     # write infra/topics.conf
    python contracts/tools/contracts.py all             # all of the above, in order
    python contracts/tools/contracts.py check           # validate + fail if any generated file is stale (CI)

Requires: fastavro, pyyaml (see requirements.txt).
"""
