# --------------------------------------------------------------------------- loading
def load_sources() -> tuple[dict[str, dict], dict[str, dict], dict[str, Path]]:
    """Return (common types by fullname, messages by fullname, path by fullname)."""
    common, messages, paths = {}, {}, {}
    for p in sorted(AVRO.rglob("*.avsc")):
        s = json.loads(p.read_text())
        full = f"{s['namespace']}.{s['name']}"
        paths[full] = p
        (common if p.parent.name == "common" else messages)[full] = s
    return common, messages, paths


def load_catalogue() -> dict:
    return yaml.safe_load(TOPICS_YAML.read_text())


def rel_to_fullname(rel: str) -> str:
    ctx, _kind, name = rel.split("/")
    return f"{NS}.{ctx}.{name}"


# --------------------------------------------------------------------------- bundling
def bundle_one(schema: dict, common: dict[str, dict]) -> dict:
    """Inline every referenced common type the first time it appears (Avro's rule)."""
    defined: set[str] = set()

    def walk(node, ns):
        if isinstance(node, str):
            full = node if "." in node else f"{ns}.{node}"
            if full in common and full not in defined:
                return walk(copy.deepcopy(common[full]), ns)
            return node
        if isinstance(node, list):
            return [walk(n, ns) for n in node]
        if isinstance(node, dict):
            t = node.get("type")
            if t in ("record", "enum", "fixed"):
                own_ns = node.get("namespace", ns)
                defined.add(f"{own_ns}.{node['name']}")
                if t == "record":
                    for fld in node["fields"]:
                        fld["type"] = walk(fld["type"], own_ns)
                return node
            if t == "array":
                node["items"] = walk(node["items"], ns)
                return node
            if t == "map":
                node["values"] = walk(node["values"], ns)
                return node
            if isinstance(t, (dict, list)) or (isinstance(t, str) and t not in PRIMITIVES):
                node["type"] = walk(t, ns)
            return node
        return node

    return walk(copy.deepcopy(schema), schema["namespace"])


PRIMITIVES = {"null", "boolean", "int", "long", "float", "double", "bytes", "string"}


def bundled_all() -> dict[str, dict]:
    common, messages, _ = load_sources()
    return {full: bundle_one(s, common) for full, s in messages.items()}


# --------------------------------------------------------------------------- validation
def validate() -> list[str]:
    errors: list[str] = []
    common, messages, paths = load_sources()
    cat = load_catalogue()

    # 1. Every schema parses once bundled.
    bundles = {}
    for full, s in messages.items():
        try:
            b = bundle_one(s, common)
            parse_schema(b)
            bundles[full] = b
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{full}: does not parse: {exc}")
    for full, s in common.items():
        try:
            parse_schema(bundle_one(s, {k: v for k, v in common.items() if k != full}))
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{full}: common type does not parse: {exc}")

    # 2. Structural rules.
    for full, s in {**common, **messages}.items():
        p = paths[full]
        if p.stem != s["name"]:
            errors.append(f"{p}: file name must equal record name {s['name']}")
        ctx = p.parent.name if p.parent.name == "common" else p.parent.parent.name
        if s["namespace"] != f"{NS}.{ctx}":
            errors.append(f"{full}: namespace must be {NS}.{ctx}")
        if not s.get("doc"):
            errors.append(f"{full}: missing doc")
    for full, s in messages.items():
        if s["fields"][0] != {"name": "envelope", "type": f"{NS}.common.Envelope", "doc": "Shared metadata. Always the first field."}:
            errors.append(f"{full}: first field must be the shared envelope")
        kind = paths[full].parent.name
        if kind not in ("events", "commands"):
            errors.append(f"{full}: must live under events/ or commands/")
        for err in lint_fields(full, s):
            errors.append(err)

    # 3. Catalogue consistency.
    owners: dict[str, str] = {}
    groups = set(cat["consumerGroups"])
    names = [t["name"] for t in cat["topics"]]
    if len(names) != len(set(names)):
        errors.append("topics.yaml: duplicate topic name")
    for t in cat["topics"]:
        if not re.fullmatch(r"[a-z]+\.[a-z-]+\.v\d+", t["name"]):
            errors.append(f"{t['name']}: name must match <context>.<stream>.v<N>")
        for c in t["consumers"]:
            if c not in groups:
                errors.append(f"{t['name']}: consumer {c} is not in consumerGroups")
        for rel in t["messages"]:
            full = rel_to_fullname(rel)
            if full not in messages:
                errors.append(f"{t['name']}: message {rel} has no schema")
                continue
            if full in owners:
                errors.append(f"{full}: listed on {owners[full]} and {t['name']}; a record belongs to one topic")
            owners[full] = t["name"]
            if not t.get("aggregate"):
                errors.append(f"{t['name']}: missing aggregate")
            fields = {f["name"] for f in messages[full]["fields"]}
            if t["key"] not in fields:
                errors.append(f"{full}: has no field '{t['key']}' to use as the partition key of {t['name']}")
            is_cmd = "/commands/" in rel
            if is_cmd != (t["kind"] == "commands"):
                errors.append(f"{full}: command/event placed on a topic of kind {t['kind']}")
    for full in messages:
        if full not in owners:
            errors.append(f"{full}: not published on any topic in topics.yaml")
    return errors


def lint_fields(full: str, record: dict) -> list[str]:
    errs = []

    def walk(node, where):
        if isinstance(node, list):
            if "null" in node and node[0] != "null":
                errs.append(f"{where}: put null first in optional unions")
            for n in node:
                walk(n, where)
        elif isinstance(node, dict):
            t = node.get("type")
            if t == "enum":
                if node.get("default") not in node["symbols"]:
                    errs.append(f"{where}: enum {node['name']} needs a default symbol (forward compatibility)")
            elif t == "record":
                for fld in node["fields"]:
                    w = f"{where}.{fld['name']}"
                    if isinstance(fld["type"], list) and "null" in fld["type"] and fld.get("default", "MISSING") is not None:
                        errs.append(f"{w}: optional field must default to null")
                    if fld["name"].lower() in ("amount", "price") and fld["type"] in ("double", "float"):
                        errs.append(f"{w}: money must use common.Money")
                    walk(fld["type"], w)
            elif t == "array":
                walk(node["items"], where)
            elif t == "map":
                walk(node["values"], where)

    walk(record, full)
    return errs


# --------------------------------------------------------------------------- examples
TS_EXAMPLE = 1_795_000_000_000  # 2026-11-18T09:46:40Z


def example_for(schema: dict, topic: dict, full: str) -> dict:
    seed = full

    def ident(name):
        return str(uuid.uuid5(uuid.NAMESPACE_URL, f"{seed}/{name}"))

    order_id = str(uuid.uuid5(uuid.NAMESPACE_URL, "example-order"))
    named: dict[str, dict] = {}

    def gen(t, fname):
        if isinstance(t, list):
            non_null = [x for x in t if x != "null"]
            return gen(non_null[0], fname)
        if isinstance(t, str):
            if t in named:
                return gen(named[t], fname)
            return primitive(t, fname)
        typ = t["type"]
        if typ == "record":
            named[t["name"]] = t
            named[f"{t.get('namespace', '')}.{t['name']}"] = t
            return {fl["name"]: gen(fl["type"], fl["name"]) for fl in t["fields"]}
        if typ == "enum":
            named[t["name"]] = t
            named[f"{t.get('namespace', '')}.{t['name']}"] = t
            return t["symbols"][0]
        if typ == "array":
            return [gen(t["items"], fname)]
        if typ == "map":
            return {"colour": "red"}
        if typ == "long" and t.get("logicalType") == "timestamp-millis":
            return TS_EXAMPLE
        return primitive(typ, fname)

    def primitive(t, fname):
        if t == "string":
            return string_value(fname)
        if t == "int":
            return {"quantity": 2, "version": 1, "ttlSeconds": 900, "attempt": 1}.get(fname, 1)
        if t == "long":
            return {"amountMinor": 1999, "sizeBytes": 48213}.get(fname, 1)
        if t == "boolean":
            return False
        if t in ("double", "float"):
            return 1.0
        if t == "bytes":
            return b"\x00"
        raise ValueError(t)

    def string_value(fname):
        fixed = {
            "orderId": order_id, "currency": "EUR", "countryCode": "DE", "contactEmail": "jane.doe@example.com",
            "sku": "SKU-1001", "store": "s3", "contentType": "application/pdf", "carrier": "fake-carrier",
            "trackingNumber": "FC123456789DE", "invoiceNumber": "INV-2026-000123", "rmaNumber": "RMA-2026-000042",
            "priceListId": "retail-eu", "postalCode": "10115", "city": "Berlin", "recipientName": "Jane Doe",
            "line1": "Invalidenstrasse 1", "sha256": hashlib.sha256(b"example").hexdigest(),
            "bucket": "invoices", "producer": topic["producers"][0], "template": "order-confirmed.v1",
            "paymentMethodToken": "tok_visa_ok", "name": "Trail Running Shoe", "productName": "Trail Running Shoe",
        }
        if fname in fixed:
            return fixed[fname]
        if fname == "objectKey":
            return f"order/2026/11/{order_id}/invoice.pdf"
        if fname.endswith("Id") or fname == "eventId":
            return ident(fname)
        return f"example-{fname}"

    value = gen(schema, "")
    env = value["envelope"]
    env.update({
        "type": full, "version": int(topic["name"].rsplit(".v", 1)[1]), "correlationId": order_id,
        "causationId": ident("causation"), "traceparent": "00-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-01",
        "tracestate": None, "tenantId": None, "expiresAt": None, "aggregateVersion": 1,
        "partitionKey": value.get(topic["key"]), "aggregateType": topic["aggregate"],
        "aggregateId": value.get(topic["key"]),
    })
    return value


def normalise(v):
    """Turn reader output (datetimes for timestamp-millis) back into the writer's plain values."""
    import datetime as dt
    if isinstance(v, dict):
        return {k: normalise(x) for k, x in v.items()}
    if isinstance(v, list):
        return [normalise(x) for x in v]
    if isinstance(v, dt.datetime):
        return int(v.timestamp() * 1000)
    return v


def build_examples() -> dict[Path, bytes]:
    cat = load_catalogue()
    bundles = bundled_all()
    out: dict[Path, bytes] = {}
    for t in cat["topics"]:
        for rel in t["messages"]:
            full = rel_to_fullname(rel)
            schema = bundles[full]
            parsed = parse_schema(schema)
            value = example_for(schema, t, full)
            avro_validate(value, parsed, raise_errors=True)
            buf = io.BytesIO()
            schemaless_writer(buf, parsed, value)
            raw = buf.getvalue()
            back = schemaless_reader(io.BytesIO(raw), parsed, return_record_name=False)
            if normalise(back) != value:
                raise AssertionError(f"{full}: Avro round trip changed the example")
            out[EXAMPLES / f"{full}.json"] = (json.dumps(value, indent=2) + "\n").encode()
            out[EXAMPLES / f"{full}.bin"] = raw
    return out


# --------------------------------------------------------------------------- generated docs
def to_ms(v: str) -> int:
    if v == "forever":
        return -1
    n, unit = int(v[:-1]), v[-1]
    return n * {"s": 1000, "m": 60_000, "h": 3_600_000, "d": 86_400_000}[unit]


def all_topics(cat: dict) -> list[dict]:
    """Business topics plus the retry and DLQ topics derived from retryPolicy."""
    rows = []
    for t in cat["topics"]:
        rows.append({"name": t["name"], "partitions": t["partitions"], "cleanup": t["cleanupPolicy"],
                     "retention_ms": to_ms(t["retention"])})
    rp = cat["retryPolicy"]
    for g in cat["consumerGroups"]:
        for d in rp["delays"]:
            rows.append({"name": f"{g}.retry.{d}", "partitions": rp["retryPartitions"], "cleanup": "delete",
                         "retention_ms": to_ms(rp["retryRetention"])})
        rows.append({"name": f"{g}.dlq", "partitions": rp["dlqPartitions"], "cleanup": "delete",
                     "retention_ms": to_ms(rp["dlqRetention"])})
    return rows


def render_topics_conf() -> str:
    cat = load_catalogue()
    lines = [f"# {GENERATED_HEADER}",
             "# name partitions cleanup.policy retention.ms",
             "# Read by infra/scripts/create-topics.sh. Replication factor comes from the RF environment variable."]
    for r in all_topics(cat):
        lines.append(f"{r['name']} {r['partitions']} {r['cleanup']} {r['retention_ms']}")
    return "\n".join(lines) + "\n"


def camel(s: str) -> str:
    parts = re.split(r"[.\-]", s)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


