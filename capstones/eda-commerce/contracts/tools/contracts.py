# --------------------------------------------------------------------------- outputs
def planned_outputs() -> dict[Path, bytes]:
    out: dict[Path, bytes] = {}
    for full, b in bundled_all().items():
        out[BUNDLED / f"{full}.avsc"] = (json.dumps(b, indent=2) + "\n").encode()
    out.update(build_examples())
    out[ASYNCAPI] = render_asyncapi().encode()
    out[TOPICS_CONF] = render_topics_conf().encode()
    return out


def write(paths_filter=None) -> None:
    for p, data in planned_outputs().items():
        if paths_filter and not paths_filter(p):
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        print(f"wrote {p.relative_to(ROOT)}")


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd in ("validate", "check", "all"):
        errs = validate()
        for e in errs:
            print(f"ERROR {e}")
        if errs:
            return 1
        print("schemas and catalogue: OK")
    if cmd == "bundle":
        write(lambda p: p.parent == BUNDLED)
    elif cmd == "examples":
        write(lambda p: p.parent == EXAMPLES)
    elif cmd == "asyncapi":
        write(lambda p: p == ASYNCAPI)
    elif cmd == "topics-conf":
        write(lambda p: p == TOPICS_CONF)
    elif cmd == "all":
        write()
    elif cmd == "check":
        stale = [p for p, d in planned_outputs().items() if not p.exists() or p.read_bytes() != d]
        for p in stale:
            print(f"STALE {p.relative_to(ROOT)} (run: python contracts/tools/contracts.py all)")
        if stale:
            return 1
        print("generated files: up to date")
    elif cmd != "validate":
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
